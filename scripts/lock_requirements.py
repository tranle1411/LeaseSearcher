"""Regenerate exact web/dev pins after installing requirements/dev.in in a clean venv."""

from importlib.metadata import distribution, distributions
from pathlib import Path
from packaging.requirements import Requirement

roots = [
    "fastapi",
    "uvicorn",
    "pydantic",
    "SQLAlchemy",
    "psycopg",
    "psycopg-binary",
    "alembic",
    "openpyxl",
    "httpx",
]
selected = {}
pending = list(roots)
while pending:
    name = pending.pop()
    dist = distribution(name)
    canonical = dist.metadata["Name"].lower().replace("_", "-")
    if canonical in selected:
        continue
    selected[canonical] = f"{dist.metadata['Name']}=={dist.version}"
    for raw in dist.requires or []:
        req = Requirement(raw)
        if req.marker is None or req.marker.evaluate():
            pending.append(req.name)
Path("requirements/web.txt").write_text(
    "# Generated by scripts/lock_requirements.py\n"
    + "\n".join(selected[k] for k in sorted(selected))
    + "\n"
)
all_pins = sorted(
    f"{d.metadata['Name']}=={d.version}"
    for d in distributions()
    if d.metadata["Name"].lower() not in {"pip", "setuptools"}
)
Path("requirements/dev.txt").write_text(
    "# Generated exact development environment\n" + "\n".join(all_pins) + "\n"
)
